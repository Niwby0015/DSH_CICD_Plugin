import type { BuildPlan } from './types.js'

const RUNTIME_IMAGES: Record<BuildPlan['language'], string> = {
  'java-maven': 'eclipse-temurin:21-jre',
  'java-gradle': 'eclipse-temurin:21-jre',
  node: 'node:22-bookworm-slim',
  python: 'python:3.12-slim',
  go: 'gcr.io/distroless/static-debian12:nonroot',
  custom: 'debian:bookworm-slim',
}

function runLines(plan: BuildPlan): string[] {
  const lines: string[] = []
  if (plan.installCommand) lines.push(`RUN ${plan.installCommand}`)
  if (plan.buildCommand) lines.push(`RUN ${plan.buildCommand}`)
  return lines
}

function entrypointJson(plan: BuildPlan): string {
  const defaultEntrypoint = plan.language === 'go'
    ? ['/app']
    : plan.language === 'node'
      ? ['npm', 'start']
      : plan.language === 'python'
        ? ['python', 'main.py']
        : ['java', '-jar', '/app/app.jar']
  const entrypoint = defaultEntrypoint
  return JSON.stringify(entrypoint)
}

export function generateDockerfile(plan: BuildPlan, entrypoint?: string[]): string {
  const runtime = RUNTIME_IMAGES[plan.language]
  const lines = [
    '# syntax=docker/dockerfile:1',
    '# Generated by dsh-plugin-cicd. Review the entrypoint and artifact path before production.',
    `FROM ${plan.toolchainImage} AS build`,
    'WORKDIR /src',
    'COPY . .',
    ...runLines(plan),
    '',
    `FROM ${runtime} AS runtime`,
    'WORKDIR /app',
  ]

  if (plan.language === 'java-maven' || plan.language === 'java-gradle') {
    const artifact = plan.language === 'java-maven' ? '/src/target/*.jar' : '/src/build/libs/*.jar'
    lines.push(`COPY --from=build ${artifact} /app/app.jar`)
    lines.push('USER 10001')
    lines.push(`ENTRYPOINT ${JSON.stringify(entrypoint ?? ['java', '-jar', '/app/app.jar'])}`)
  } else if (plan.language === 'go') {
    lines.push('COPY --from=build /out/app /app')
    lines.push('USER nonroot:nonroot')
    lines.push(`ENTRYPOINT ${JSON.stringify(entrypoint ?? ['/app'])}`)
  } else if (plan.language === 'node' || plan.language === 'python') {
    lines.push('COPY --from=build /src /app')
    lines.push(plan.language === 'node' ? 'USER node' : 'USER 10001')
    lines.push(`ENTRYPOINT ${JSON.stringify(entrypoint ?? entrypointJson(plan))}`)
  } else {
    lines.push('COPY --from=build /src /app')
    lines.push('USER 10001')
    lines.push(`ENTRYPOINT ${JSON.stringify(entrypoint ?? ['/app/run.sh'])}`)
  }
  return `${lines.join('\n')}\n`
}
