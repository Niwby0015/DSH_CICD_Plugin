import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const outdir = resolve(root, 'dist')

await mkdir(resolve(outdir, 'host'), { recursive: true })

await build({
  entryPoints: [resolve(root, 'src/host/index.ts')],
  outfile: resolve(outdir, 'host/index.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  sourcemap: false,
  legalComments: 'none',
  external: ['node:*', '@deepseek-ai/dsh-*', '@deepseek-ai/cordis'],
  banner: { js: '// Generated by dsh-plugin-cicd build.mjs. Do not edit.' },
  logLevel: 'info',
})

const client = await build({
  entryPoints: [resolve(root, 'src/client/index.tsx')],
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'cjs',
  target: 'es2020',
  sourcemap: false,
  legalComments: 'none',
  external: ['react'],
  jsxFactory: 'h',
  jsxFragment: 'Fragment',
  loader: { '.ts': 'ts', '.tsx': 'tsx' },
  logLevel: 'silent',
})

const body = client.outputFiles[0]?.text ?? ''
const wrapped = `// Generated by dsh-plugin-cicd build.mjs. Do not edit.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
    ${body}
    return module.exports;
  },
});
`
await writeFile(resolve(outdir, 'client.js'), wrapped, 'utf8')
console.log(`built ${pkg.name}: dist/host/index.js, dist/client.js`)
